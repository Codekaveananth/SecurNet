import React from 'react'
import { ConfusionMatrix, GroupedBars, HBars } from '../components/charts.jsx'
import { ErrorNote, Panel, Skeleton, Stat } from '../components/ui.jsx'

const f3 = (v) => (typeof v === 'number' ? v.toFixed(3) : '—')

export default function Model({ metrics, status }) {
  if (metrics.loading) return <div className="page"><h1>Model performance</h1><Skeleton lines={6} /></div>
  const m = metrics.data
  if (!m) {
    return (
      <div className="page">
        <header className="page-head"><h1>Model performance</h1></header>
        <ErrorNote>
          <strong>Metrics unavailable.</strong> They are served by the ML service from its training artifacts. Start it on
          port 8000 and reload. No figures are shown rather than placeholders.
        </ErrorNote>
      </div>
    )
  }
  const u = m.url || {}
  const s = m.sms || {}
  const ab = m.leakage_ablation
  const prov = m.provenance

  return (
    <div className="page">
      <header className="page-head">
        <h1>Model performance</h1>
        <p className="lead">
          Every number on this page is read live from the training artifacts in <code>ml-service/artifacts</code>. Nothing is typed in by hand.
        </p>
      </header>

      {prov?.dataset === 'synthetic' && (
        <div className="notice" role="note">
          <strong>These results come from a synthetic corpus.</strong> The shipped models were trained on data generated by{' '}
          <code>training/build_dataset.py</code>, built to be realistic (hard negatives, class overlap, 2% label noise,
          domain-grouped splits) but not collected from live phishing feeds. Quote them with that qualification.
        </div>
      )}

      {u.test && (
        <>
          <h2 className="section-title">Link model</h2>
          <p className="section-sub">
            XGBoost on {u.config?.n_features ?? '—'} lexical features, {u.config?.n_samples?.toLocaleString()} URLs, split{' '}
            {u.config?.split === 'grouped_by_registrable_domain' ? 'by registrable domain so no domain appears in both training and test' : u.config?.split}.
            Leakage-prone features {u.config?.leakage_features_included ? 'included' : 'excluded'}.
          </p>
          <dl className="kpis">
            <Stat label="Accuracy" value={f3(u.test.accuracy)} />
            <Stat label="Precision" value={f3(u.test.precision)} />
            <Stat label="Recall" value={f3(u.test.recall)} />
            <Stat label="F1" value={f3(u.test.f1)} />
            <Stat label="ROC-AUC" value={f3(u.test.roc_auc)} />
            <Stat label="False positive rate" value={f3(u.test.false_positive_rate)} tone="watch" />
          </dl>
          <div className="grid-3">
            <Panel title="Test split confusion matrix" description={`${u.config?.n_test?.toLocaleString()} URLs at threshold ${u.test.threshold?.toFixed(2)}.`}>
              <ConfusionMatrix cm={u.test.confusion_matrix} />
            </Panel>
            <Panel title="Validation compared with test">
              {u.validation ? (
                <GroupedBars
                  groups={['accuracy', 'precision', 'recall', 'f1', 'roc_auc'].map((k) => ({
                    label: { accuracy: 'Acc', precision: 'Prec', recall: 'Rec', f1: 'F1', roc_auc: 'AUC' }[k],
                    val: u.validation[k], test: u.test[k]
                  }))}
                  series={[{ key: 'val', label: 'Validation', color: 'var(--line-strong)' }, { key: 'test', label: 'Test', color: 'var(--signal)' }]}
                />
              ) : <p className="muted">No validation results in the artifact.</p>}
            </Panel>
            <Panel title="Speed and training">
              <dl className="kv">
                <div><dt>Single inference</dt><dd>{u.timing?.single_inference_ms} ms</dd></div>
                <div><dt>Feature extraction</dt><dd>{u.timing?.featurise_ms_per_url} ms per URL</dd></div>
                <div><dt>Training time</dt><dd>{u.timing?.train_seconds} s</dd></div>
                <div><dt>Boosting rounds used</dt><dd>{u.config?.best_iteration}</dd></div>
                <div><dt>Train / validation / test</dt><dd>{[u.config?.n_train, u.config?.n_val, u.config?.n_test].map((x) => x?.toLocaleString()).join(' / ')}</dd></div>
                <div><dt>Serving threshold</dt><dd>{status.ml?.url_threshold ?? u.test.threshold?.toFixed(2)}</dd></div>
              </dl>
            </Panel>
          </div>
          {u.top_features_by_gain && (
            <Panel title="Feature importance" description="Total gain per feature in the trained model.">
              <HBars data={u.top_features_by_gain.map(([label, value]) => ({ label, value, tone: 'info' }))} label="URL feature importance by gain" format={(v) => v.toFixed(1)} />
            </Panel>
          )}
        </>
      )}

      {ab?.configurations && (
        <>
          <h2 className="section-title">Leakage control</h2>
          <p className="section-sub">
            The central methodology. Each configuration was trained {ab.repeats} times on {ab.corpus_size?.toLocaleString()} URLs
            ({ab.distinct_domains?.toLocaleString()} distinct domains). Leaky features record how a feed formatted the URL, not whether it is a phish.
          </p>
          <Panel>
            <div className="table-wrap">
              <table className="data">
                <thead>
                  <tr>
                    <th scope="col"></th><th scope="col">Configuration</th>
                    <th scope="col" className="num">Accuracy</th><th scope="col" className="num">F1</th>
                    <th scope="col" className="num">ROC-AUC</th><th scope="col" className="num">Shared domains</th>
                  </tr>
                </thead>
                <tbody>
                  {Object.entries(ab.configurations).map(([k, c]) => (
                    <tr key={k} className={k === 'D' ? 'row-hl' : ''}>
                      <th scope="row">{k}</th>
                      <td>{c.label}{k === 'D' ? ' (deployed)' : ''}</td>
                      <td className="num mono">{f3(c.accuracy.mean)} <span className="muted">±{c.accuracy.std.toFixed(3)}</span></td>
                      <td className="num mono">{f3(c.f1.mean)}</td>
                      <td className="num mono">{f3(c.roc_auc.mean)}</td>
                      <td className="num mono">{c.shared_domains_train_test}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            {ab.accuracy_inflation_pp != null && (
              <p className="callout">
                Accuracy inflation attributable to leakage: <strong>{ab.accuracy_inflation_pp} percentage points</strong> (A compared with D).
                {prov?.dataset === 'synthetic' && ' On the synthetic corpus the 2% label-noise ceiling caps how high the leaky configuration can climb, so the gap on real merged feeds may be larger.'}
              </p>
            )}
          </Panel>
        </>
      )}

      {s.test && (
        <>
          <h2 className="section-title">Message model</h2>
          <p className="section-sub">{s.config?.classifier} over {s.config?.vectoriser}, {s.config?.n_samples?.toLocaleString()} messages.</p>
          <dl className="kpis">
            <Stat label="Accuracy" value={f3(s.test.accuracy)} />
            <Stat label="Precision" value={f3(s.test.precision)} />
            <Stat label="Recall" value={f3(s.test.recall)} />
            <Stat label="F1" value={f3(s.test.f1)} />
            <Stat label="ROC-AUC" value={f3(s.test.roc_auc)} />
            {s.cross_validation && <Stat label={`${s.cross_validation.folds}-fold CV F1`} value={`${f3(s.cross_validation.f1_mean)} ± ${s.cross_validation.f1_std.toFixed(3)}`} />}
          </dl>
          <div className="grid-2">
            <Panel title="Test split confusion matrix" description={`${s.config?.n_test?.toLocaleString()} messages.`}>
              <ConfusionMatrix cm={s.test.confusion_matrix} labels={['Legitimate', 'Scam']} />
            </Panel>
            <Panel title="Cross-validation F1 per fold">
              {s.cross_validation ? (
                <HBars data={s.cross_validation.f1_per_fold.map((v, i) => ({ label: `Fold ${i + 1}`, value: v, tone: 'info' }))}
                  label="F1 per cross-validation fold" format={(v) => v.toFixed(4)} max={1} />
              ) : <p className="muted">Not in the artifact.</p>}
              <p className="muted small">Single inference {s.timing?.single_inference_ms} ms.</p>
            </Panel>
          </div>
        </>
      )}
    </div>
  )
}
